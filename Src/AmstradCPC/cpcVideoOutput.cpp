    CVideoOutput::CVideoOutput(CMachine *pMachine) : inherited(pMachine)
    {
        ResetVars();
    }

    void CVideoOutput::ResetVars()
    {
        m_HSyncActive = false;
        m_VSyncActive = false;
        m_beamX = 0;
        m_beamY = 0;
        m_frameCount = 0;
    }

