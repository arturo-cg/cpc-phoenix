    void CVideoOutput::Oscillator::Initialize(int _idealPeriod)
    {
        period = _idealPeriod;
        counter = 0;
        gateArrayCounter = 0;
        offset = 0;
    }

    bool CVideoOutput::Oscillator::Tick()
    {
        counter++;
        gateArrayCounter++;

        if (counter >= period)
        {
            counter = 0;
            // Offset our counter to be in sync with the CRTC (H or V) SYNC signal.
            // TODO: Do this gradually to give it the analog feel that CRT monitors had.
            //////int offsetDiff = gateArrayCounter - offset;
            //////offset += min(offsetDiff, 64 * 5);
            // For now, the sync happens immediately.
            offset = gateArrayCounter;
            return true;
        }
        else
        {
            return false;
        }
    }

    void CVideoOutput::Oscillator::OnGateArraySync()
    {
        period = gateArrayCounter;
        gateArrayCounter = 0;
    }

    int CVideoOutput::Oscillator::OffsetCounter() const
    {
        return (counter + offset) % period;
    }

