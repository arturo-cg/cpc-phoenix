    unsigned CVideoOutput::GetBeamX() const
    {
        return m_horizontalOscillator.OffsetCounter();
    }

    unsigned CVideoOutput::GetBeamY() const
    {
        return m_verticalOscillator.OffsetCounter() / IdealScanlinePeriod;
    }

    void CVideoOutput::Run()
    {
        //
        // This runs on a 1 Mhz clock. Each pulse (i.e. each time CVideoOutput::Run is called), the beam advances 16 mode 2 pixels.
        //

        // Draw physical pixels.
        int beamX = GetBeamX();
        int beamY = GetBeamY();

        if ((((beamX + 1) * CGateArray::NUM_PHYSICAL_PIXELS_PER_CYCLE) <= BUFFER_WIDTH) &&    // Make sure we don't write outside of the buffer.
            (beamY < BUFFER_HEIGHT))
        {
            // The RGB values for the pixels are generated by the Gate Array.
            const unsigned* pixelRGBs = m_machine->GetGateArray()->GetGeneratedPhysicalPixels();
            // +- Calculate the pointer to the buffer that corresponds to the current beam position.
            static const unsigned BytesPerPixel = 4;
            const SBufferProperties& bufferProps = GetBufferProperties();
            unsigned char* destination = bufferProps.data + (beamY * bufferProps.nStride) + (beamX * CGateArray::NUM_PHYSICAL_PIXELS_PER_CYCLE * BytesPerPixel);
            KMASSERT(GetBufferProperties().eFormat == PIXELFORMAT_B8G8R8A8);
            memcpy(destination, pixelRGBs, CGateArray::NUM_PHYSICAL_PIXELS_PER_CYCLE * BytesPerPixel);
        }

        // Horizontal and vertical oscillators.
        m_horizontalOscillator.Tick();
        if (m_verticalOscillator.Tick())
        {
            // Let the client know that the monitor just completed a frame.
            OnBufferComplete();
        }
    }

